package com.abood.third_proto.w04.client;

import com.abood.third_proto.w04.W04Registry;
import com.mojang.blaze3d.buffers.GpuBuffer;
import com.mojang.blaze3d.buffers.Std140Builder;
import com.mojang.blaze3d.buffers.Std140SizeCalculator;
import com.mojang.blaze3d.pipeline.RenderPipeline;
import com.mojang.blaze3d.pipeline.RenderTarget;
import com.mojang.blaze3d.pipeline.TextureTarget;
import com.mojang.blaze3d.shaders.UniformType;
import com.mojang.blaze3d.systems.CommandEncoder;
import com.mojang.blaze3d.systems.RenderPass;
import com.mojang.blaze3d.systems.RenderSystem;
import com.mojang.blaze3d.textures.FilterMode;
import com.mojang.logging.LogUtils;
import java.util.OptionalInt;
import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.GuiGraphics;
import net.minecraft.client.renderer.MappableRingBuffer;
import net.minecraft.client.renderer.RenderPipelines;
import net.minecraft.resources.Identifier;
import org.slf4j.Logger;

/**
 * Step 2 look (options 3 + 4): our own full-screen pass over the finished world image.
 * Runs while the HUD is still being collected, so it sees world + hand and the HUD is drawn on top afterwards.
 * Vanilla post_effect JSON cannot take per-frame values in 1.21.11, so this pass and its uniform buffer are ours.
 */
final class ShaderTunnelRenderer implements TunnelRenderer {
    private static final Logger LOGGER = LogUtils.getLogger();

    // Not registered on purpose: an unregistered pipeline compiles on first use, so a broken shader
    // only logs an error (and we fall back) instead of failing the whole resource reload.
    private static final RenderPipeline PIPELINE = RenderPipeline.builder(RenderPipelines.POST_PROCESSING_SNIPPET)
            .withLocation(Identifier.fromNamespaceAndPath(W04Registry.MODID, "pipeline/tunnel_vision"))
            .withVertexShader(Identifier.withDefaultNamespace("core/screenquad"))
            .withFragmentShader(Identifier.fromNamespaceAndPath(W04Registry.MODID, "post/tunnel_vision"))
            .withSampler("InSampler")
            .withUniform("TunnelConfig", UniformType.UNIFORM_BUFFER)
            .build();

    // Must match the TunnelConfig block in tunnel_vision.fsh, field by field
    private static final int CONFIG_SIZE = new Std140SizeCalculator()
            .putVec2()   // Center
            .putFloat()  // Radius
            .putFloat()  // Feather
            .putFloat()  // Aspect
            .putFloat()  // Time
            .putFloat()  // Intensity
            .putFloat()  // Padding (keeps the block a multiple of 16 bytes)
            .get();

    // Soft edge width = FEATHER_BASE + FEATHER_SCALE * hole radius (fractions of the screen height)
    private static final float FEATHER_BASE = 0.03F;
    private static final float FEATHER_SCALE = 0.6F;

    private MappableRingBuffer configBuffer;
    private TextureTarget sceneCopy;
    private boolean reportedFailure;

    @Override
    public boolean render(GuiGraphics graphics, TunnelFrame frame) {
        if (!RenderSystem.getDevice().precompilePipeline(PIPELINE).isValid()) {
            if (!reportedFailure) {
                LOGGER.error("[W0-4] tunnel_vision shader did not compile, using the GUI mask instead. The GLSL error is logged just above.");
                reportedFailure = true;
            }
            return false;
        }
        reportedFailure = false;

        RenderTarget main = Minecraft.getInstance().getMainRenderTarget();
        ensureResources(main.width, main.height);
        CommandEncoder encoder = RenderSystem.getDevice().createCommandEncoder();

        // A pass cannot read and write the same texture, so it reads a copy of this frame's image
        encoder.copyTextureToTexture(main.getColorTexture(), sceneCopy.getColorTexture(), 0, 0, 0, 0, 0, main.width, main.height);
        writeConfig(encoder, frame, (float) main.width / main.height);

        try (RenderPass pass = encoder.createRenderPass(() -> "third_proto tunnel vision", main.getColorTextureView(), OptionalInt.empty())) {
            pass.setPipeline(PIPELINE);
            pass.setUniform("TunnelConfig", configBuffer.currentBuffer());
            pass.bindTexture("InSampler", sceneCopy.getColorTextureView(), RenderSystem.getSamplerCache().getClampToEdge(FilterMode.LINEAR));
            pass.draw(0, 3); // one full-screen triangle, generated by vanilla core/screenquad
        }
        configBuffer.rotate();
        return true;
    }

    private void writeConfig(CommandEncoder encoder, TunnelFrame frame, float aspect) {
        TunnelHole hole = frame.hole();
        float radius = hole.radius() / frame.guiHeight();
        float feather = radius > 0.0F ? FEATHER_BASE + FEATHER_SCALE * radius : 0.001F;
        try (GpuBuffer.MappedView view = encoder.mapBuffer(configBuffer.currentBuffer(), false, true)) {
            Std140Builder.intoBuffer(view.data())
                    .putVec2(hole.x() / frame.guiWidth(), 1.0F - hole.y() / frame.guiHeight()) // GUI y goes down, texture y goes up
                    .putFloat(radius)
                    .putFloat(feather)
                    .putFloat(aspect)
                    .putFloat(frame.timeSeconds())
                    .putFloat(frame.intensity())
                    .putFloat(0.0F);
        }
    }

    private void ensureResources(int width, int height) {
        if (configBuffer == null) {
            configBuffer = new MappableRingBuffer(() -> "third_proto tunnel config",
                    GpuBuffer.USAGE_UNIFORM | GpuBuffer.USAGE_MAP_WRITE, CONFIG_SIZE);
        }
        if (sceneCopy == null) {
            sceneCopy = new TextureTarget("third_proto tunnel scene copy", width, height, false);
        } else if (sceneCopy.width != width || sceneCopy.height != height) {
            sceneCopy.resize(width, height);
        }
    }
}
